"""SQLite metadata store + JSON dataset files.

Metadata (one row per scrape session) lives in SQLite. The full dataset is
written to ``<data>/sessions/<session_id>.json`` and the row stores only the
generated file name. File names are generated by the app, never taken from user
input, and are re-validated against the sessions directory on every access.
"""
from __future__ import annotations

import io
import sqlite3
from contextlib import contextmanager
from pathlib import Path

import pandas as pd

import config
from analytics.data_cleaning import ensure_schema
from database.models import ScrapeSession
from utils.helpers import is_valid_session_id
from utils.logger import get_logger

logger = get_logger("database")


class DatabaseError(Exception):
    """User-presentable database failure."""


_SCHEMA = """
CREATE TABLE IF NOT EXISTS sessions (
    session_id        TEXT PRIMARY KEY,
    url               TEXT NOT NULL,
    domain            TEXT NOT NULL DEFAULT '',
    created_at        TEXT NOT NULL,
    records_count     INTEGER NOT NULL DEFAULT 0,
    pages_processed   INTEGER NOT NULL DEFAULT 0,
    status            TEXT NOT NULL,
    duration_seconds  REAL NOT NULL DEFAULT 0,
    template          TEXT NOT NULL DEFAULT 'generic',
    dataset_file      TEXT,
    message           TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_sessions_created ON sessions(created_at DESC);
"""


class DatabaseManager:
    def __init__(self, db_path: Path | str = config.DB_PATH, sessions_dir: Path | str = config.SESSIONS_DIR):
        self.db_path = Path(db_path)
        self.sessions_dir = Path(sessions_dir)
        try:
            self.db_path.parent.mkdir(parents=True, exist_ok=True)
            self.sessions_dir.mkdir(parents=True, exist_ok=True)
            with self._connect() as conn:
                conn.executescript(_SCHEMA)
        except (OSError, sqlite3.Error) as exc:
            logger.exception("Could not initialise database")
            raise DatabaseError("The local database could not be initialised.") from exc

    @contextmanager
    def _connect(self):
        conn = sqlite3.connect(self.db_path, timeout=10)
        conn.row_factory = sqlite3.Row
        try:
            yield conn
            conn.commit()
        except sqlite3.Error:
            conn.rollback()
            raise
        finally:
            conn.close()

    # ------------------------------------------------------------------
    def _dataset_path(self, filename: str) -> Path:
        base = self.sessions_dir.resolve()
        path = (base / filename).resolve()
        if path.parent != base or path.suffix != ".json":
            raise DatabaseError("Invalid dataset location.")
        return path

    def save_session(self, session: ScrapeSession, df: pd.DataFrame | None = None) -> ScrapeSession:
        """Insert a session row and (if ``df`` is given and non-empty) persist the dataset."""
        if not is_valid_session_id(session.session_id):
            raise DatabaseError("Invalid session id.")
        try:
            if df is not None and not df.empty:
                filename = f"{session.session_id}.json"
                self._dataset_path(filename).write_text(
                    ensure_schema(df).to_json(orient="records", force_ascii=False), encoding="utf-8"
                )
                session.dataset_file = filename
            with self._connect() as conn:
                conn.execute(
                    """INSERT OR REPLACE INTO sessions
                       (session_id, url, domain, created_at, records_count, pages_processed, status,
                        duration_seconds, template, dataset_file, message)
                       VALUES (:session_id, :url, :domain, :created_at, :records_count, :pages_processed,
                               :status, :duration_seconds, :template, :dataset_file, :message)""",
                    session.to_dict(),
                )
        except (OSError, sqlite3.Error) as exc:
            logger.exception("Failed to save session %s", session.session_id)
            raise DatabaseError("The scraping session could not be saved.") from exc
        return session

    def list_sessions(self, limit: int | None = None) -> list[ScrapeSession]:
        sql = "SELECT * FROM sessions ORDER BY created_at DESC"
        params: tuple = ()
        if limit:
            sql += " LIMIT ?"
            params = (int(limit),)
        try:
            with self._connect() as conn:
                return [ScrapeSession.from_row(r) for r in conn.execute(sql, params).fetchall()]
        except sqlite3.Error as exc:
            logger.exception("Failed to list sessions")
            raise DatabaseError("The history could not be read.") from exc

    def sessions_dataframe(self) -> pd.DataFrame:
        sessions = self.list_sessions()
        return pd.DataFrame([s.to_dict() for s in sessions]) if sessions else pd.DataFrame(
            columns=list(ScrapeSession.__dataclass_fields__)
        )

    def get_session(self, session_id: str) -> ScrapeSession | None:
        if not is_valid_session_id(session_id):
            return None
        try:
            with self._connect() as conn:
                row = conn.execute("SELECT * FROM sessions WHERE session_id = ?", (session_id,)).fetchone()
            return ScrapeSession.from_row(row) if row else None
        except sqlite3.Error as exc:
            raise DatabaseError("The session could not be read.") from exc

    def load_dataset(self, session_id: str) -> pd.DataFrame | None:
        """Return the saved dataset, or ``None`` if it is unavailable (e.g. wiped by a redeploy)."""
        session = self.get_session(session_id)
        if not session or not session.dataset_file:
            return None
        try:
            path = self._dataset_path(session.dataset_file)
            if not path.exists():
                return None
            return ensure_schema(pd.read_json(io.StringIO(path.read_text(encoding="utf-8")), orient="records"))
        except (OSError, ValueError) as exc:
            logger.exception("Failed to load dataset for %s", session_id)
            raise DatabaseError("The saved dataset could not be loaded.") from exc

    def delete_session(self, session_id: str) -> bool:
        session = self.get_session(session_id)
        if not session:
            return False
        try:
            if session.dataset_file:
                self._dataset_path(session.dataset_file).unlink(missing_ok=True)
            with self._connect() as conn:
                conn.execute("DELETE FROM sessions WHERE session_id = ?", (session_id,))
            return True
        except (OSError, sqlite3.Error) as exc:
            logger.exception("Failed to delete session %s", session_id)
            raise DatabaseError("The session could not be deleted.") from exc

    def clear_history(self) -> int:
        sessions = self.list_sessions()
        for s in sessions:
            self.delete_session(s.session_id)
        return len(sessions)

    def get_stats(self) -> dict:
        try:
            with self._connect() as conn:
                row = conn.execute(
                    "SELECT COUNT(*) AS n, COALESCE(SUM(pages_processed),0) AS pages, "
                    "COALESCE(SUM(records_count),0) AS records FROM sessions"
                ).fetchone()
            return {"sessions": row["n"], "urls_processed": row["pages"], "records": row["records"]}
        except sqlite3.Error as exc:
            raise DatabaseError("Statistics could not be read.") from exc
